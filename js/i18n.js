/** 按浏览器语言识别演示页语言（纯自动，无手动切换入口） */
function detectLang() {
    const lang = (navigator.language || 'en').toLowerCase();
    if (lang.startsWith('zh')) {
        return (lang.includes('tw') || lang.includes('hk') || lang.includes('hant')) ? 'zhTW' : 'zh';
    }
    if (lang.startsWith('en')) return 'en';
    if (lang.startsWith('ja')) return 'ja';
    if (lang.startsWith('ko')) return 'ko';
    if (lang.startsWith('fr')) return 'fr';
    if (lang.startsWith('de')) return 'de';
    if (lang.startsWith('ru')) return 'ru';
    return 'en';
}

/** 应用语言到页面静态文案（[data-i18n] / [data-i18n-placeholder]） */
function applyLang(lang) {
    const dict = I18N[lang] || I18N.en;
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        let text = dict[el.dataset.i18n] ?? el.dataset.i18n;
        if (el.dataset.i18nArgs) text = text.replace('{n}', el.dataset.i18nArgs);
        // 只替换最后一个文本节点，保留子元素（如 radio 的 <input>），
        // 避免 textContent 整体赋值把子元素清空。
        let lastText = null;
        const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null);
        while (walker.nextNode()) lastText = walker.currentNode;
        if (lastText) {
            lastText.textContent = text;
        } else {
            el.textContent = text;
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        el.placeholder = dict[el.dataset.i18nPlaceholder] ?? el.dataset.i18nPlaceholder;
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
        el.title = dict[el.dataset.i18nTitle] ?? el.dataset.i18nTitle;
    });
}

// 页面加载即按浏览器语言应用
applyLang(detectLang());
